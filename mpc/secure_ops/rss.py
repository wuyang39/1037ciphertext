"""Deterministic 3-party RSS arithmetic over ``Z_(2^bits)``.

The implementation models the three parties explicitly while retaining a
single-process execution mode for local tests. Multiplication uses Beaver
triples generated by the test-only preprocessing provider. The production SPU
must replace that provider with a proven RSS preprocessing protocol.
"""

from __future__ import annotations

import random
import time
from dataclasses import dataclass
from typing import Any, Iterable, Sequence


class RSSProtocolError(ValueError):
    """An RSS operation received inconsistent shares or metadata."""


@dataclass(frozen=True)
class OperationTrace:
    """Redacted per-operator trace fields allowed to leave the TEE."""

    operation: str
    shape: tuple[int, ...]
    ring: str
    scale: int
    range: tuple[int, int]
    rounds: int
    bytes: int
    elapsed_ms: float
    simulated_reveal: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "operation": self.operation,
            "shape": list(self.shape),
            "ring": self.ring,
            "scale": self.scale,
            "range": list(self.range),
            "rounds": self.rounds,
            "bytes": self.bytes,
            "elapsed_ms": self.elapsed_ms,
            "simulated_reveal": self.simulated_reveal,
        }


@dataclass(frozen=True)
class SharedTensor:
    """One flat share per configured party plus the logical tensor shape."""

    shares: tuple[tuple[int, ...], ...]
    shape: tuple[int, ...]
    ring_bits: int

    def __post_init__(self) -> None:
        if len(self.shares) != 3:
            raise RSSProtocolError("3PC RSS requires exactly three shares")
        length = len(self.shares[0])
        if any(len(share) != length for share in self.shares):
            raise RSSProtocolError("party shares must have equal length")
        expected = 1
        for dimension in self.shape:
            if not isinstance(dimension, int) or dimension < 0:
                raise RSSProtocolError("tensor shape dimensions must be non-negative")
            expected *= dimension
        if expected != length:
            raise RSSProtocolError("share length does not match the tensor shape")
        mask = (1 << self.ring_bits) - 1
        if any(value < 0 or value > mask for share in self.shares for value in share):
            raise RSSProtocolError("a share is outside the ring")

    @property
    def size(self) -> int:
        return len(self.shares[0])

    def party_share(self, party_index: int) -> tuple[int, ...]:
        if not 0 <= party_index < 3:
            raise RSSProtocolError("party index must be 0, 1, or 2")
        return self.shares[party_index]


def _product(shape: Sequence[int]) -> int:
    result = 1
    for dimension in shape:
        result *= dimension
    return result


def _flatten(value: Any) -> tuple[tuple[int, ...], tuple[int, ...]]:
    if isinstance(value, bool):
        raise TypeError("bool is not an RSS numeric input")
    if isinstance(value, int):
        return (value,), ()
    if not isinstance(value, (list, tuple)):
        raise TypeError("RSS inputs must be integers or nested lists")
    if not value:
        return (), (0,)
    flat: list[int] = []
    child_shapes: list[tuple[int, ...]] = []
    for child in value:
        child_flat, child_shape = _flatten(child)
        flat.extend(child_flat)
        child_shapes.append(child_shape)
    if any(shape != child_shapes[0] for shape in child_shapes[1:]):
        raise RSSProtocolError("nested input is not rectangular")
    return tuple(flat), (len(value), *child_shapes[0])


def _nest(flat: Sequence[int], shape: Sequence[int]) -> Any:
    if not shape:
        if len(flat) != 1:
            raise RSSProtocolError("scalar shape requires one value")
        return int(flat[0])
    if len(shape) == 1:
        return [int(value) for value in flat]
    stride = _product(shape[1:])
    return [
        _nest(flat[index * stride : (index + 1) * stride], shape[1:])
        for index in range(shape[0])
    ]


def _round_half_away(numerator: int, denominator: int) -> int:
    if denominator <= 0:
        raise ValueError("denominator must be positive")
    if numerator >= 0:
        return (numerator + denominator // 2) // denominator
    return -((-numerator + denominator // 2) // denominator)


class RSSContext:
    """Local 3-party RSS topology and arithmetic engine."""

    def __init__(
        self,
        *,
        ring_bits: int = 64,
        seed: int | None = None,
        reveal_allowed: bool = True,
    ) -> None:
        if ring_bits < 8 or ring_bits > 128:
            raise ValueError("ring_bits must be in [8, 128]")
        self.ring_bits = ring_bits
        self.modulus = 1 << ring_bits
        self.mask = self.modulus - 1
        self.reveal_allowed = reveal_allowed
        self.parties = ("P0", "P1", "P2")
        self._rng = random.Random(seed)
        self._traces: list[OperationTrace] = []

    @property
    def traces(self) -> tuple[OperationTrace, ...]:
        return tuple(self._traces)

    def clear_traces(self) -> None:
        self._traces.clear()

    def _random_share(self) -> int:
        return self._rng.randrange(self.modulus)

    def _share_flat(self, flat: Sequence[int]) -> tuple[tuple[int, ...], ...]:
        parties: list[list[int]] = [[], [], []]
        for value in flat:
            normalized = int(value) & self.mask
            first = self._random_share()
            second = self._random_share()
            third = (normalized - first - second) & self.mask
            parties[0].append(first)
            parties[1].append(second)
            parties[2].append(third)
        return tuple(tuple(party) for party in parties)

    def _record(
        self,
        *,
        operation: str,
        result: SharedTensor,
        started: float,
        rounds: int,
        simulated_reveal: bool = False,
        scale: int = 1,
        communication_bytes: int | None = None,
    ) -> SharedTensor:
        values = [value for share in result.shares for value in share]
        value_range = (0, 0) if not values else (min(values), max(values))
        if communication_bytes is None:
            communication_bytes = result.size * max(1, rounds) * 8
        self._traces.append(
            OperationTrace(
                operation=operation,
                shape=result.shape,
                ring=f"Z_2^{self.ring_bits}",
                scale=scale,
                range=value_range,
                rounds=rounds,
                bytes=communication_bytes,
                elapsed_ms=(time.perf_counter() - started) * 1000.0,
                simulated_reveal=simulated_reveal,
            )
        )
        return result

    def record_external(
        self,
        *,
        operation: str,
        result: SharedTensor,
        started: float,
        rounds: int,
        simulated_reveal: bool = False,
        scale: int = 1,
        communication_bytes: int | None = None,
    ) -> SharedTensor:
        """Record an operation implemented by the local secure-op adapter."""
        return self._record(
            operation=operation,
            result=result,
            started=started,
            rounds=rounds,
            simulated_reveal=simulated_reveal,
            scale=scale,
            communication_bytes=communication_bytes,
        )

    def share(self, value: Any) -> SharedTensor:
        flat, shape = _flatten(value)
        result = SharedTensor(
            shares=self._share_flat(flat),
            shape=shape,
            ring_bits=self.ring_bits,
        )
        started = time.perf_counter()
        return self._record(
            operation="share_input",
            result=result,
            started=started,
            rounds=1,
        )

    def reconstruct(self, shared: SharedTensor) -> Any:
        self._require_shared(shared)
        flat = [
            sum(party[index] for party in shared.shares) & self.mask
            for index in range(shared.size)
        ]
        return _nest(flat, shared.shape)

    def reconstruct_signed(self, shared: SharedTensor) -> Any:
        value = self.reconstruct(shared)
        sign = 1 << (self.ring_bits - 1)

        def signed_scalar(item: int) -> int:
            return item - self.modulus if item & sign else item

        def walk(item: Any) -> Any:
            if isinstance(item, list):
                return [walk(child) for child in item]
            return signed_scalar(int(item))

        return walk(value)

    def add(self, left: SharedTensor, right: SharedTensor) -> SharedTensor:
        self._require_pair(left, right)
        started = time.perf_counter()
        shares = tuple(
            tuple(
                (left.shares[party][index] + right.shares[party][index]) & self.mask
                for index in range(left.size)
            )
            for party in range(3)
        )
        return self._record(
            operation="rss_add",
            result=SharedTensor(shares, left.shape, self.ring_bits),
            started=started,
            rounds=0,
        )

    def subtract(self, left: SharedTensor, right: SharedTensor) -> SharedTensor:
        self._require_pair(left, right)
        started = time.perf_counter()
        shares = tuple(
            tuple(
                (left.shares[party][index] - right.shares[party][index]) & self.mask
                for index in range(left.size)
            )
            for party in range(3)
        )
        return self._record(
            operation="rss_sub",
            result=SharedTensor(shares, left.shape, self.ring_bits),
            started=started,
            rounds=0,
        )

    def scalar_mul(self, shared: SharedTensor, scalar: int) -> SharedTensor:
        self._require_shared(shared)
        normalized = int(scalar) & self.mask
        started = time.perf_counter()
        shares = tuple(
            tuple((value * normalized) & self.mask for value in party)
            for party in shared.shares
        )
        return self._record(
            operation="rss_scalar_mul",
            result=SharedTensor(shares, shared.shape, self.ring_bits),
            started=started,
            rounds=0,
        )

    def mul(self, left: SharedTensor, right: SharedTensor) -> SharedTensor:
        self._require_pair(left, right)
        started = time.perf_counter()
        result = self._mul_no_trace(left, right)
        return self._record(
            operation="rss_mul",
            result=result,
            started=started,
            rounds=2,
        )

    def _mul_no_trace(
        self,
        left: SharedTensor,
        right: SharedTensor,
    ) -> SharedTensor:
        result_parties: list[list[int]] = [[], [], []]
        for index in range(left.size):
            a = self._random_share()
            b = self._random_share()
            c = (a * b) & self.mask
            a_shares = self._share_flat((a,))
            b_shares = self._share_flat((b,))
            c_shares = self._share_flat((c,))
            x = (
                left.shares[0][index]
                + left.shares[1][index]
                + left.shares[2][index]
            ) & self.mask
            y = (
                right.shares[0][index]
                + right.shares[1][index]
                + right.shares[2][index]
            ) & self.mask
            d = (x - a) & self.mask
            e = (y - b) & self.mask
            for party in range(3):
                value = (
                    c_shares[party][0]
                    + d * b_shares[party][0]
                    + e * a_shares[party][0]
                    + (d * e if party == 0 else 0)
                ) & self.mask
                result_parties[party].append(value)
        return SharedTensor(
            shares=tuple(tuple(party) for party in result_parties),
            shape=left.shape,
            ring_bits=self.ring_bits,
        )

    def matmul(self, left: SharedTensor, right: SharedTensor) -> SharedTensor:
        if len(left.shape) != 2 or len(right.shape) != 2:
            raise RSSProtocolError("rss_matmul requires two-dimensional tensors")
        rows, inner = left.shape
        right_inner, columns = right.shape
        if inner != right_inner:
            raise RSSProtocolError("rss_matmul inner dimensions do not match")
        started = time.perf_counter()
        output_parties: list[list[int]] = [[], [], []]
        for row in range(rows):
            for column in range(columns):
                accumulator = self._zero_scalar()
                for index in range(inner):
                    left_element = self._scalar_slice(left, row * inner + index)
                    right_element = self._scalar_slice(
                        right,
                        index * columns + column,
                    )
                    product = self._mul_no_trace(left_element, right_element)
                    accumulator = self._add_no_trace(accumulator, product)
                for party in range(3):
                    output_parties[party].append(accumulator.shares[party][0])
        result = SharedTensor(
            shares=tuple(tuple(party) for party in output_parties),
            shape=(rows, columns),
            ring_bits=self.ring_bits,
        )
        return self._record(
            operation="rss_matmul",
            result=result,
            started=started,
            rounds=2,
            communication_bytes=rows * columns * inner * 3 * 8,
        )

    def truncate(
        self,
        shared: SharedTensor,
        *,
        shift_bits: int,
        scale: int = 1,
    ) -> SharedTensor:
        if shift_bits < 0:
            raise ValueError("shift_bits must be non-negative")
        self._require_shared(shared)
        started = time.perf_counter()
        signed = self.reconstruct_signed(shared)

        def truncate_scalar(value: int) -> int:
            return _round_half_away(int(value), 1 << shift_bits)

        def walk(value: Any) -> Any:
            if isinstance(value, list):
                return [walk(child) for child in value]
            return truncate_scalar(int(value))

        result = self.share(walk(signed))
        return self._record(
            operation="rss_truncate",
            result=result,
            started=started,
            rounds=1,
            simulated_reveal=True,
            scale=scale,
        )

    def compare(
        self,
        left: SharedTensor,
        right: SharedTensor,
        *,
        operation: str = "rss_compare",
    ) -> SharedTensor:
        self._require_pair(left, right)
        if not self.reveal_allowed:
            raise RSSProtocolError("secure compare simulator requires reveal mode")
        started = time.perf_counter()
        left_value = self.reconstruct_signed(left)
        right_value = self.reconstruct_signed(right)

        def walk(a: Any, b: Any) -> Any:
            if isinstance(a, list):
                return [walk(child_a, child_b) for child_a, child_b in zip(a, b)]
            return 1 if int(a) >= int(b) else 0

        result = self.share(walk(left_value, right_value))
        return self._record(
            operation=operation,
            result=result,
            started=started,
            rounds=1,
            simulated_reveal=True,
        )

    def reciprocal(
        self,
        denominator: SharedTensor,
        *,
        scale: int,
        zero_value: int = 0,
    ) -> SharedTensor:
        if not self.reveal_allowed:
            raise RSSProtocolError("reciprocal simulator requires reveal mode")
        if scale <= 0:
            raise ValueError("scale must be positive")
        started = time.perf_counter()
        value = self.reconstruct_signed(denominator)

        def walk(item: Any) -> Any:
            if isinstance(item, list):
                return [walk(child) for child in item]
            denominator_value = int(item)
            if denominator_value == 0:
                return zero_value
            return _round_half_away(scale, denominator_value)

        result = self.share(walk(value))
        return self._record(
            operation="rss_reciprocal",
            result=result,
            started=started,
            rounds=1,
            simulated_reveal=True,
        )

    def _zero_scalar(self) -> SharedTensor:
        return SharedTensor(
            shares=((0,), (0,), (0,)),
            shape=(),
            ring_bits=self.ring_bits,
        )

    def _scalar_slice(self, tensor: SharedTensor, index: int) -> SharedTensor:
        return SharedTensor(
            shares=tuple((share[index],) for share in tensor.shares),
            shape=(),
            ring_bits=self.ring_bits,
        )

    def _add_no_trace(
        self,
        left: SharedTensor,
        right: SharedTensor,
    ) -> SharedTensor:
        return SharedTensor(
            shares=tuple(
                tuple(
                    (left.shares[party][index] + right.shares[party][index])
                    & self.mask
                    for index in range(left.size)
                )
                for party in range(3)
            ),
            shape=left.shape,
            ring_bits=self.ring_bits,
        )

    def _require_shared(self, shared: SharedTensor) -> None:
        if not isinstance(shared, SharedTensor):
            raise RSSProtocolError("expected an RSS SharedTensor")
        if shared.ring_bits != self.ring_bits:
            raise RSSProtocolError("share ring does not match the topology")

    def _require_pair(self, left: SharedTensor, right: SharedTensor) -> None:
        self._require_shared(left)
        self._require_shared(right)
        if left.shape != right.shape:
            raise RSSProtocolError("RSS operands must have the same shape")


